k = int(input())

if k < 0:
    print('Мы не находили грибы, а только теряли')
elif k == 0:
    print('Мы нашли в лесу 0 грибов')
else:
   
    if 11 <= k % 100 <= 14:
        w = 'грибов'
    elif k % 10 == 1:
        w = 'гриб'
    elif k % 10 in (2, 3, 4):
        w = 'гриба'
    else:
        w = 'грибов'

    print('Мы нашли в лесу', k, w)
